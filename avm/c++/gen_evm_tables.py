"""Writes evm_tables.h: hf_ofdm_common._true_err2's calibration curves
(simulated once in Python with numpy's normal generator) as constants for
modem_rx.cpp. Rerun if that simulation changes."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, ".."))
import hf_ofdm_common as ofdm
out = ["// generated by gen_evm_tables.py from hf_ofdm_common._true_err2 -- do not edit", "#pragma once", ""]
for name, mod in (("QPSK", "qpsk"), ("QAM16", "16qam"), ("QAM32", "32qam")):
    ofdm._true_err2(0.1, mod)
    meas, true = ofdm._DD_TABLES[mod]
    out.append(f"static const int EVM_N_{name} = {len(meas)};")
    out.append(f"static const double EVM_MEAS_{name}[] = {{" + ", ".join(repr(float(v)) for v in meas) + "};")
    out.append(f"static const double EVM_TRUE_{name}[] = {{" + ", ".join(repr(float(v)) for v in true) + "};")
open(os.path.join(here, "evm_tables.h"), "w").write("\n".join(out) + "\n")
